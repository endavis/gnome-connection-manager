# Default retry settings.  Override with env vars DOIT_GH_RETRIES and
# DOIT_GH_BACKOFF_BASE.
_GH_DEFAULT_RETRIES = 3
_GH_DEFAULT_BACKOFF_BASE = 2.0  # seconds
_GH_BACKOFF_FACTOR = 2.5

# Transient-error markers that warrant a retry.
_TRANSIENT_MARKERS: tuple[str, ...] = (
    r"5\d\d",
    "gateway timeout",
    "bad gateway",
    "service unavailable",
    "internal server error",
    "unicorn!",
    "connection refused",
    "connection reset",
    "could not resolve host",
    "i/o timeout",
    "context deadline exceeded",
)

# PR title must follow conventional-commits format. ``release`` is allowed so
# release PRs generated by ``doit release`` (titled ``release: v<version>``)
# merge through ``doit pr_merge``. Matches the same allowance in the CI title
# check and ``validate_merge_commits`` (#653, #655).
_PR_TITLE_PATTERN = re.compile(
    r"^(feat|fix|refactor|docs|test|chore|ci|perf|release)(\(.+\))?:\s.+"
)

# GitHub refuses ``gh pr merge`` on a PR in a native stack with "This pull
# request is part of a stack and must be merged using the asynchronous merge
# REST API." ``doit pr_merge`` does not support stacks (#847, #853).
_STACKED_PR_MARKER = "part of a stack"


def _is_transient_gh_error(stderr: str) -> str | None:
    """Return the matched transient-error marker, or ``None`` if not transient.

    Checks ``stderr`` (case-insensitively) against the list of known transient
    markers.  HTTP 5xx status codes are matched via a regex pattern; all other
    markers are plain substring checks.

    Args:
        stderr: The stderr text from a failed ``gh`` invocation.

    Returns:
        The matched marker string when the error is transient, ``None`` otherwise.
    """
    lowered = stderr.lower()
    for marker in _TRANSIENT_MARKERS:
        if marker.startswith(r"5"):
            # Regex pattern for HTTP 5xx codes.
            if re.search(marker, lowered):
                return marker
        else:
            if marker in lowered:
                return marker
    return None


def _run_gh_with_retry(
    cmd: list[str],
    *,
    retries: int | None = None,
    backoff_base: float | None = None,
    **subprocess_kwargs: Any,  # noqa: ANN401 - forwarded verbatim to subprocess.run
) -> subprocess.CompletedProcess[str]:
    """Run a ``gh`` command with exponential-backoff retry on transient errors.

    Drop-in replacement for ``subprocess.run([...gh...], ...)``.  Adds retry
    logic around transient 5xx / network failures while leaving all other
    error-handling semantics intact (``check=True`` re-raises
    :class:`subprocess.CalledProcessError` after exhaustion; ``check=False``
    returns the :class:`subprocess.CompletedProcess` as-is).

    The helper forces ``capture_output=True, text=True`` when neither is
    already set, so it can inspect ``stderr`` for transient markers.

    Args:
        cmd: The command argument list (must start with ``"gh"``).
        retries: Number of *retry* attempts after the first failure.  Defaults
            to ``DOIT_GH_RETRIES`` env var, or :data:`_GH_DEFAULT_RETRIES`.
            ``0`` means a single attempt with no retry.
        backoff_base: Base delay in seconds for the exponential backoff.
            Defaults to ``DOIT_GH_BACKOFF_BASE`` env var, or
            :data:`_GH_DEFAULT_BACKOFF_BASE`.
        **subprocess_kwargs: Forwarded to :func:`subprocess.run`.

    Returns:
        The :class:`subprocess.CompletedProcess` result from the (eventually)
        successful attempt.

    Raises:
        subprocess.CalledProcessError: When ``check=True`` (the default) and
            all retry attempts are exhausted.
    """
    console = Console()

    if retries is None:
        retries = int(os.environ.get("DOIT_GH_RETRIES", _GH_DEFAULT_RETRIES))
    if backoff_base is None:
        backoff_base = float(os.environ.get("DOIT_GH_BACKOFF_BASE", _GH_DEFAULT_BACKOFF_BASE))

    # Ensure we can read stderr for transient-error classification.
    if "capture_output" not in subprocess_kwargs and "stdout" not in subprocess_kwargs:
        subprocess_kwargs["capture_output"] = True
    if "text" not in subprocess_kwargs:
        subprocess_kwargs["text"] = True

    check: bool = subprocess_kwargs.pop("check", True)

    max_attempts = retries + 1
    last_exc: subprocess.CalledProcessError | None = None

    for attempt in range(1, max_attempts + 1):
        try:
            result: subprocess.CompletedProcess[str] = subprocess.run(
                cmd, check=True, **subprocess_kwargs
            )
            return result
        except subprocess.CalledProcessError as exc:
            stderr_text = (exc.stderr or "") if isinstance(exc.stderr, str) else ""
            marker = _is_transient_gh_error(stderr_text)

            if marker is None:
                # Non-transient failure — honour check semantics immediately.
                if check:
                    raise
                # check=False: return a CompletedProcess reflecting the failure.
                return subprocess.CompletedProcess(
                    args=exc.cmd,
                    returncode=exc.returncode,
                    stdout=exc.stdout or "",
                    stderr=exc.stderr or "",
                )

            last_exc = exc
            if attempt >= max_attempts:
                break

            delay = backoff_base * (_GH_BACKOFF_FACTOR ** (attempt - 1))
            jitter = random.uniform(0, delay * 0.1)  # nosec B311
            total = delay + jitter
            console.print(
                verbatim(
                    f"Retry {attempt}/{retries}: {' '.join(cmd[:3])} "
                    f"(transient: {marker}, sleeping {total:.1f}s)",
                    "yellow",
                )
            )
            time.sleep(total)

    # All retries exhausted.
    if check:
        assert last_exc is not None
        raise last_exc
    # check=False path after exhaustion — return last failure as CompletedProcess.
    assert last_exc is not None
    return subprocess.CompletedProcess(
        args=last_exc.cmd,
        returncode=last_exc.returncode,
        stdout=last_exc.stdout or "",
        stderr=last_exc.stderr or "",
    )


def _get_editor() -> str:
    """Get the user's preferred editor."""
    return os.environ.get("EDITOR", os.environ.get("VISUAL", "vi"))


def _open_editor_with_template(template: str, suffix: str = ".md") -> str | None:
    """Open editor with template and return the edited content.

    Args:
        template: The template content to start with
        suffix: File suffix for the temp file

    Returns:
        The edited content (without comment lines), or None if aborted/unchanged
    """
    console = Console()
    editor = _get_editor()

    # Create temp file with template
    with tempfile.NamedTemporaryFile(mode="w", suffix=suffix, delete=False, encoding="utf-8") as f:
        f.write(template)
        temp_path = f.name

    try:
        # Open editor
        console.print(verbatim(f"Opening {editor}...", "dim"))
        result = subprocess.run([editor, temp_path])

        if result.returncode != 0:
            console.print("[red]Editor exited with error.[/red]")
            return None

        # Read the edited content
        with open(temp_path, encoding="utf-8") as f:
            content = f.read()

        # Remove comment lines (starting with #) and HTML comments
        lines = []
        for line in content.split("\n"):
            stripped = line.strip()
            if stripped.startswith("#") and not stripped.startswith("##"):
                continue  # Skip comment lines but keep ## headers
            lines.append(line)

        edited = "\n".join(lines)

        # Remove HTML comments <!-- ... -->
        edited = re.sub(r"<!--.*?-->", "", edited, flags=re.DOTALL)

        # Clean up extra blank lines
        edited = re.sub(r"\n{3,}", "\n\n", edited).strip()

        return edited

    finally:
        # Clean up temp file
        if os.path.exists(temp_path):
            os.remove(temp_path)


def _parse_markdown_sections(content: str) -> dict[str, str]:
    """Parse markdown content into sections by ## headers.

    Args:
        content: Markdown content with ## headers

    Returns:
        Dict mapping section names to their content
    """
    sections: dict[str, str] = {}
    current_section = ""
    current_content: list[str] = []

    for line in content.split("\n"):
        if line.startswith("## "):
            # Save previous section
            if current_section:
                sections[current_section] = "\n".join(current_content).strip()
            # Start new section
            current_section = line[3:].strip()
            current_content = []
        else:
            current_content.append(line)

    # Save last section
    if current_section:
        sections[current_section] = "\n".join(current_content).strip()

    return sections


def _validate_issue_content(
    sections: dict[str, str], issue_type: str, console: "ConsoleType"
) -> bool:
    """Validate that required sections have content.

    Args:
        sections: Parsed markdown sections
        issue_type: Type of issue (feature, bug, refactor, docs, chore)
        console: Rich console for output

    Returns:
        True if valid, False otherwise
    """
    # Get required sections dynamically from templates
    required_sections = get_required_sections(issue_type)

    missing = []
    placeholder_patterns = [
        "describe the",
        "clear description",
        "paste error",
        "any other relevant",
        "delete section if not needed",
    ]

    for section_name in required_sections:
        content = sections.get(section_name, "").strip()
        if not content:
            missing.append(section_name)
            continue

        # Check for placeholder text
        content_lower = content.lower()
        for pattern in placeholder_patterns:
            if pattern in content_lower:
                console.print(
                    f"[yellow]Warning: '{section_name}' may contain placeholder text.[/yellow]"
                )
                break

    if missing:
        console.print(f"[red]Missing required sections: {', '.join(missing)}[/red]")
        return False

    return True


def _read_body_file(file_path: str, console: "ConsoleType") -> str | None:
    """Read body content from a file.

    Args:
        file_path: Path to the file
        console: Rich console for output

    Returns:
        File content, or None if error
    """
    from pathlib import Path

    path = Path(file_path)
    if not path.exists():
        console.print(verbatim(f"File not found: {file_path}", "red"))
        return None

    try:
        return path.read_text(encoding="utf-8")
    except Exception as e:
        console.print(verbatim(f"Error reading file: {e}", "red"))
        return None


def task_issue() -> dict[str, Any]:
    """Create issue from .github/ISSUE_TEMPLATE/<type>.yml (feature/bug/refactor/docs/chore).

    Labels are automatically applied based on the issue type.

    Three modes:
    1. Interactive (default): Opens $EDITOR with template
    2. --body-file: Reads body from a file
    3. --title + --body: Provides content directly (for AI/scripts)

    Examples:
        Interactive:  doit issue --type=feature
        From file:    doit issue --type=docs --title="Add guide" --body-file=issue.md
        Direct:       doit issue --type=chore --title="Update CI" --body="## Description\\n..."
    """

    def create_issue(
        type: str,
        title: str | None = None,
        body: str | None = None,
        body_file: str | None = None,
    ) -> None:
        console = Console()
        console.print()
        console.print(
            Panel.fit(
                verbatim(f"Creating {type} Issue", "bold cyan"),
                border_style="cyan",
            )
        )
        console.print()

        # Get template (validates type and retrieves labels/template dynamically)
        try:
            issue_template = get_issue_template(type)
        except ValueError as e:
            console.print(verbatim(str(e), "red"))
            sys.exit(1)
        except FileNotFoundError as e:
            console.print(verbatim(f"Template error: {e}", "red"))
            sys.exit(1)

        labels = issue_template.labels

        # Determine body content
        if body_file:
            # Mode 2: Read from file
            body_content = _read_body_file(body_file, console)
            if body_content is None:
                sys.exit(1)
        elif body:
            # Mode 3: Direct body provided
            body_content = body
        else:
            # Mode 1: Interactive editor
            console.print(
                f"[dim]Opening editor with {type} template. "
                "Fill in the sections, save, and exit.[/dim]"
            )
            body_content = _open_editor_with_template(issue_template.editor_template)
            if body_content is None:
                console.print("[yellow]Aborted.[/yellow]")
                sys.exit(0)

        # Parse and validate
        sections = _parse_markdown_sections(body_content)
        if not _validate_issue_content(sections, type, console):
            console.print("[red]Issue content validation failed.[/red]")
            console.print()
            console.print(f"[yellow]See template: .github/ISSUE_TEMPLATE/{type}.yml[/yellow]")
            sys.exit(1)

        # Get title if not provided
        if not title:
            console.print("[cyan]Issue title:[/cyan]")
            title = input("> ").strip()
            if not title:
                console.print("[red]Title is required.[/red]")
                sys.exit(1)

        # Create the issue
        console.print("\n[cyan]Creating issue...[/cyan]")
        try:
            result = _run_gh_with_retry(
                [
                    "gh",
                    "issue",
                    "create",
                    "--title",
                    title,
                    "--body",
                    body_content,
                    "--label",
                    labels,
                ],
                capture_output=True,
                text=True,
                check=True,
            )
            issue_url = result.stdout.strip()
            console.print()
            console.print(
                Panel.fit(
                    f"[bold green]Issue created successfully![/bold green]\n\n{issue_url}",
                    border_style="green",
                )
            )
        except subprocess.CalledProcessError as e:
            console.print("[red]Failed to create issue:[/red]")
            console.print(verbatim(e.stderr, "red"))
            sys.exit(1)

    return {
        "actions": [create_issue],
        "params": [
            {
                "name": "type",
                "short": "t",
                "long": "type",
                "default": "feature",
                "help": "Issue type: feature, bug, refactor, docs, chore",
            },
            {"name": "title", "long": "title", "default": None, "help": "Issue title"},
            {"name": "body", "long": "body", "default": None, "help": "Issue body (markdown)"},
            {
                "name": "body_file",
                "long": "body-file",
                "default": None,
                "help": "Read body from file",
            },
        ],
        "title": title_with_actions,
    }


def task_pr() -> dict[str, Any]:
    """Create PR from .github/pull_request_template.md (auto-detects branch and linked issue).

    Three modes:
    1. Interactive (default): Opens $EDITOR with template
    2. --body-file: Reads body from a file
    3. --title + --body: Provides content directly (for AI/scripts)

    Before creating the PR, the task verifies that the current branch is up
    to date with ``origin/main`` and aborts with a remediation message if
    it is behind. Pass ``--no-update-check`` to skip this guard.

    ``--base=<branch>`` opens the PR against another branch, for work that
    builds on an unmerged one, so its diff shows only its own changes. The
    up-to-date check then compares with ``origin/<branch>``.

    If the current branch has no upstream, the task pushes it to ``origin``
    automatically before calling ``gh pr create``. Pass ``--no-push`` to
    skip the auto-push (the task will then abort if no upstream exists).

    Examples:
        Interactive:  doit pr
        From file:    doit pr --title="feat: add export" --body-file=pr.md
        Direct:       doit pr --title="feat: add export" --body="## Description\\n..."
        Dependent:    doit pr --base=feat/41-add-parser
        Skip check:   doit pr --no-update-check
        No auto-push: doit pr --no-push
    """

    def create_pr(
        title: str | None = None,
        body: str | None = None,
        body_file: str | None = None,
        draft: bool = False,
        no_update_check: bool = False,
        no_push: bool = False,
        base: str | None = None,
    ) -> None:
        console = Console()
        console.print()
        console.print(
            Panel.fit("[bold cyan]Creating Pull Request[/bold cyan]", border_style="cyan")
        )
        console.print()

        # Check we're not on main
        current_branch = subprocess.run(
            ["git", "branch", "--show-current"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()

        if current_branch == "main":
            console.print("[red]Cannot create PR from main branch.[/red]")
            console.print("[yellow]Create a feature branch first.[/yellow]")
            sys.exit(1)

        console.print(f"[dim]Current branch: {current_branch}[/dim]")

        if no_update_check:
            console.print("[dim]Skipping up-to-date check (--no-update-check).[/dim]")
        else:
            _check_branch_up_to_date(current_branch, console, base=base or "main")

        _ensure_branch_pushed(current_branch, console, no_push)

        # Try to extract issue number from branch name (e.g., feat/42-description)
        detected_issue = None
        branch_issue_match = re.search(r"/(\d+)-", current_branch)
        if branch_issue_match:
            detected_issue = branch_issue_match.group(1)
            console.print(f"[dim]Detected issue from branch: #{detected_issue}[/dim]")

        # Determine body content
        if body_file:
            # Mode 2: Read from file
            body_content = _read_body_file(body_file, console)
            if body_content is None:
                sys.exit(1)
        elif body:
            # Mode 3: Direct body provided
            body_content = body
        else:
            # Mode 1: Interactive editor
            # Get PR template dynamically from .github/
            try:
                template = get_pr_template()
            except FileNotFoundError as e:
                console.print(verbatim(f"Template error: {e}", "red"))
                sys.exit(1)

            # Pre-fill issue number if detected
            if detected_issue:
                template = template.replace("#(issue)", f"#{detected_issue}")

            console.print(
                "[dim]Opening editor with PR template. Fill in the sections, save, and exit.[/dim]"
            )
            body_content = _open_editor_with_template(template)
            if body_content is None:
                console.print("[yellow]Aborted.[/yellow]")
                sys.exit(0)

        # Validate PR has description
        sections = _parse_markdown_sections(body_content)
        description = sections.get("Description", "").strip()
        if not description:
            console.print("[red]Description is required.[/red]")
            console.print()
            console.print("[yellow]See template: .github/pull_request_template.md[/yellow]")
            sys.exit(1)

        # Get title if not provided
        if not title:
            console.print("[cyan]PR title (e.g., 'feat: add export feature'):[/cyan]")
            title = input("> ").strip()
            if not title:
                console.print("[red]Title is required.[/red]")
                sys.exit(1)

        # Create the PR
        console.print("\n[cyan]Creating PR...[/cyan]")
        cmd = ["gh", "pr", "create", "--title", title, "--body", body_content]
        if base:
            cmd.extend(["--base", base])
        if draft:
            cmd.append("--draft")

        try:
            result = _run_gh_with_retry(cmd, capture_output=True, text=True, check=True)
            pr_url = result.stdout.strip()
            console.print()
            console.print(
                Panel.fit(
                    f"[bold green]PR created successfully![/bold green]\n\n{pr_url}",
                    border_style="green",
                )
            )
            if base and base != "main":
                console.print(f"[yellow]This PR targets '{base}', not main.[/yellow]")
                console.print(
                    "[yellow]After that branch merges, rebase onto main and retarget "
                    "(CONTRIBUTING.md, step 4):[/yellow]"
                )
                console.print(f"  gh pr edit {pr_url} --base main")
        except subprocess.CalledProcessError as e:
            console.print("[red]Failed to create PR:[/red]")
            console.print(verbatim(e.stderr, "red"))
            sys.exit(1)

    return {
        "actions": [create_pr],
        "params": [
            {"name": "title", "long": "title", "default": None, "help": "PR title"},
            {"name": "body", "long": "body", "default": None, "help": "PR body (markdown)"},
            {
                "name": "body_file",
                "long": "body-file",
                "default": None,
                "help": "Read body from file",
            },
            {
                "name": "draft",
                "long": "draft",
                "type": bool,
                "default": False,
                "help": "Create as draft PR",
            },
            {
                "name": "no_update_check",
                "long": "no-update-check",
                "type": bool,
                "default": False,
                "help": "Skip check that branch is up to date with origin/main (or --base)",
            },
            {
                "name": "no_push",
                "long": "no-push",
                "type": bool,
                "default": False,
                "help": "Do not auto-push a branch with no upstream (aborts instead)",
            },
            {
                "name": "base",
                "long": "base",
                "default": None,
                "help": "Open the PR against this branch instead of main",
            },
        ],
        "title": title_with_actions,
    }


def _fetch_issue_context(number: str, out_dir: Path, console: "ConsoleType") -> None:
    """Fetch an issue's metadata and comments and write them as JSON files.

    Writes ``issue.json`` (``number``/``title``/``body``/``labels``/``assignees``) and
    ``comments.json`` (``{"comments": [...]}}``) under *out_dir*, creating it if needed.
    Nothing is written until both the fetch succeeds, so a failure never leaves a
    partial or empty file behind.

    Args:
        number: Issue number.
        out_dir: Directory to write ``issue.json``/``comments.json`` into.
        console: Rich console for output.

    Raises:
        SystemExit: Via ``sys.exit(1)`` if the issue cannot be fetched.
    """
    try:
        result = _run_gh_with_retry(
            [
                "gh",
                "issue",
                "view",
                number,
                "--json",
                "number,title,body,labels,assignees,comments",
            ],
            capture_output=True,
            text=True,
            check=True,
        )
    except subprocess.CalledProcessError as e:
        stderr = (e.stderr or "").strip()
        console.print(verbatim(f"Failed to fetch issue #{number}: {stderr}", "red"))
        sys.exit(1)

    data: dict[str, Any] = json.loads(result.stdout)
    comments = data.pop("comments", [])

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "issue.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    (out_dir / "comments.json").write_text(
        json.dumps({"comments": comments}, indent=2), encoding="utf-8"
    )
    console.print(
        verbatim(f"Wrote {out_dir / 'issue.json'} and {out_dir / 'comments.json'}", "green")
    )


def _fetch_pr_context(number: str, out_dir: Path, console: "ConsoleType") -> None:
    """Fetch a PR's metadata and diff and write them to files.

    Writes ``pr.json`` (``number``/``title``/``body``/``baseRefName``/``headRefName``) and
    ``diff.txt`` (the raw ``gh pr diff`` output) under *out_dir*, creating it if needed.
    Nothing is written until both fetches succeed, so a failure never leaves a partial or
    empty file behind.

    Args:
        number: PR number.
        out_dir: Directory to write ``pr.json``/``diff.txt`` into.
        console: Rich console for output.

    Raises:
        SystemExit: Via ``sys.exit(1)`` if the PR cannot be fetched.
    """
    try:
        pr_result = _run_gh_with_retry(
            [
                "gh",
                "pr",
                "view",
                number,
                "--json",
                "number,title,body,baseRefName,headRefName",
            ],
            capture_output=True,
            text=True,
            check=True,
        )
    except subprocess.CalledProcessError as e:
        stderr = (e.stderr or "").strip()
        console.print(verbatim(f"Failed to fetch PR #{number}: {stderr}", "red"))
        sys.exit(1)

    try:
        diff_result = _run_gh_with_retry(
            ["gh", "pr", "diff", number],
            capture_output=True,
            text=True,
            check=True,
        )
    except subprocess.CalledProcessError as e:
        stderr = (e.stderr or "").strip()
        console.print(verbatim(f"Failed to fetch diff for PR #{number}: {stderr}", "red"))
        sys.exit(1)

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "pr.json").write_text(pr_result.stdout, encoding="utf-8")
    (out_dir / "diff.txt").write_text(diff_result.stdout, encoding="utf-8")
    console.print(verbatim(f"Wrote {out_dir / 'pr.json'} and {out_dir / 'diff.txt'}", "green"))


def task_delegation_context() -> dict[str, Any]:
    """Fetch GitHub data a delegated agent needs and write it to files it reads instead of `gh`.

    A delegated agent (another CLI invoked non-interactively) has no trusted, un-sandboxed
    `gh` of its own in every host (see `.codex/rules/gh.rules`). The **host** — the CLI the
    user is driving, which does have one — runs this task before delegating, and the
    delegated prompt reads the files it writes instead of shelling out to `gh` itself.

    Two modes:
    - ``--kind=issue``: writes ``issue.json`` (number/title/body/labels/assignees) and
      ``comments.json`` (``{"comments": [...]}}``).
    - ``--kind=pr``: writes ``pr.json`` (number/title/body/baseRefName/headRefName) and
      ``diff.txt`` (the PR's diff).

    A missing or inaccessible issue/PR aborts with `sys.exit(1)` and a clear message —
    never a silent empty file.

    By convention, *out* is ``tmp/agents/<host>/<task>-<n>/`` (for example
    ``tmp/agents/claude/multi-review-123/``). The orchestrating skill that creates it is
    responsible for deleting it once every delegated agent has returned.

    Examples:
        doit delegation_context --kind=issue --n=985 --out=tmp/agents/claude/multi-plan-985
        doit delegation_context --kind=pr --n=42 --out=tmp/agents/claude/multi-review-42
    """

    def fetch_context(kind: str = "", n: str = "", out: str = "") -> None:
        console = Console()
        console.print()
        console.print(
            Panel.fit(
                verbatim("Fetching Delegation Context", "bold cyan"),
                border_style="cyan",
            )
        )
        console.print()

        if kind not in ("issue", "pr"):
            console.print(verbatim("--kind must be 'issue' or 'pr'", "red"))
            sys.exit(1)
        if not n:
            console.print(verbatim("--n (issue or PR number) is required", "red"))
            sys.exit(1)
        if not out:
            console.print(verbatim("--out (output directory) is required", "red"))
            sys.exit(1)

        out_dir = Path(out)
        if kind == "issue":
            _fetch_issue_context(n, out_dir, console)
        else:
            _fetch_pr_context(n, out_dir, console)

    return {
        "actions": [fetch_context],
        "params": [
            {
                "name": "kind",
                "long": "kind",
                "default": "",
                "help": "Context kind: 'issue' or 'pr'",
            },
            {"name": "n", "long": "n", "default": "", "help": "Issue or PR number"},
            {
                "name": "out",
                "long": "out",
                "default": "",
                "help": "Output directory to write context files into (created if missing)",
            },
        ],
        "title": title_with_actions,
    }


def _get_pr_info(pr_number: str | None, console: "ConsoleType") -> dict[str, Any] | None:
    """Get PR information from GitHub API.

    Args:
        pr_number: PR number, or None to use current branch's PR
        console: Rich console for output

    Returns:
        Dict with PR info, or None if not found
    """
    import json

    cmd = [
        "gh",
        "pr",
        "view",
        "--json",
        "number,title,body,state,baseRefName,headRefName,isCrossRepository",
    ]
    if pr_number:
        cmd.append(pr_number)

    try:
        result = _run_gh_with_retry(cmd, capture_output=True, text=True, check=True)
        data: dict[str, Any] = json.loads(result.stdout)
        return data
    except subprocess.CalledProcessError as e:
        if "no pull requests found" in e.stderr.lower():
            console.print("[red]No PR found for current branch.[/red]")
        else:
            console.print(verbatim(f"Failed to get PR info: {e.stderr}", "red"))
        return None


def _get_default_branch(console: "ConsoleType") -> str:
    """Return the repository's default branch, or ``main`` if GitHub can't say.

    Args:
        console: Rich console for the fallback warning

    Returns:
        The default branch name (for example ``main``).
    """
    try:
        result = _run_gh_with_retry(
            ["gh", "repo", "view", "--json", "defaultBranchRef", "--jq", ".defaultBranchRef.name"],
            capture_output=True,
            text=True,
            check=True,
        )
    except subprocess.CalledProcessError as e:
        console.print(verbatim(f"Could not read the default branch: {e.stderr}", "yellow"))
        console.print("[yellow]Assuming 'main'.[/yellow]")
        return "main"
    return result.stdout.strip() or "main"


def _extract_linked_issues(body: str) -> list[str]:
    """Extract linked issue numbers from PR body.

    Looks for patterns like:
    - Addresses #123

    Args:
        body: PR body text

    Returns:
        List of issue numbers referenced with "Addresses"
    """
    seen: set[str] = set()
    result: list[str] = []

    pattern = r"^Addresses\s+#(\d+)"
    for match in re.finditer(pattern, body, re.MULTILINE):
        issue = match.group(1)
        if issue not in seen:
            seen.add(issue)
            result.append(issue)

    return result


def _format_merge_subject(title: str, pr_number: int, issues: list[str]) -> str:
    """Format the merge commit subject line.

    Args:
        title: PR title (should be in conventional commit format)
        pr_number: PR number
        issues: List of issue numbers referenced with "Addresses"

    Returns:
        Formatted subject: "<type>: <subject> (merges PR #XX, addresses #YY)"
    """
    # Build the suffix parts
    parts = [f"merges PR #{pr_number}"]

    if issues:
        issue_refs = ", ".join(f"#{i}" for i in issues)
        parts.append(f"addresses {issue_refs}")

    suffix = f"({', '.join(parts)})"
    return f"{title} {suffix}"


def _close_linked_issues(issues: list[str], pr_number: int, console: Console) -> None:
    """Close each linked issue via `gh issue close` with a standard comment.

    On per-issue failure, prints a yellow warning and continues. Does not
    raise — the merge has already succeeded, partial failure is reported
    but not fatal.

    Args:
        issues: List of issue numbers to close.
        pr_number: PR number used in the close comment.
        console: Rich console for output.
    """
    if not issues:
        console.print("[dim]No linked issues to close.[/dim]")
        return

    comment = f"Addressed in PR #{pr_number}"
    for issue in issues:
        try:
            _run_gh_with_retry(
                ["gh", "issue", "close", issue, "--comment", comment],
                check=True,
                capture_output=True,
                text=True,
            )
            console.print(f"[green]Closed issue #{issue}[/green]")
        except subprocess.CalledProcessError as e:
            stderr = (e.stderr or "").strip()
            console.print(verbatim(f"Failed to close #{issue}: {stderr}", "yellow"))


def _worktree_holding(pr_info: dict[str, Any]) -> Path | None:
    """Return the linked worktree that has the PR's branch checked out, if any (#863).

    A cross-repository PR's branch lives in the fork, so it is not looked up.
    """
    branch = pr_info.get("headRefName")
    if not branch or pr_info.get("isCrossRepository"):
        return None
    try:
        return worktree_for_branch(branch)
    except (subprocess.CalledProcessError, OSError):
        return None


def _merged_head(pr_number: int, console: Console) -> str | None:
    """Return the head commit PR *pr_number* merged, or ``None`` if it has not merged.

    Nothing is deleted until GitHub reports the PR as merged.
    """
    try:
        result = _run_gh_with_retry(
            ["gh", "pr", "view", str(pr_number), "--json", "state,headRefOid"],
            capture_output=True,
            text=True,
            check=True,
        )
    except subprocess.CalledProcessError as e:
        stderr = (e.stderr or "").strip()
        console.print(verbatim(f"Could not read the state of PR #{pr_number}: {stderr}", "yellow"))
        return None
    data: dict[str, Any] = json.loads(result.stdout)
    if data.get("state") != "MERGED":
        console.print(f"[yellow]PR #{pr_number} is {data.get('state')}, not merged yet.[/yellow]")
        return None
    head: str = data.get("headRefOid") or ""
    return head


def _delete_remote_branch(branch: str, console: Console) -> None:
    """Delete *branch* on GitHub, as ``gh pr merge --delete-branch`` would.

    Skipped when the repository deletes head branches on merge itself.
    """
    setting = _run_gh_with_retry(
        ["gh", "repo", "view", "--json", "deleteBranchOnMerge", "--jq", ".deleteBranchOnMerge"],
        capture_output=True,
        text=True,
        check=False,
    )
    if setting.returncode == 0 and setting.stdout.strip() == "true":
        return
    # Quoted, so a "#" or "?" in the name cannot cut the endpoint short and name
    # a different branch.
    ref = quote(f"heads/{branch}", safe="/")
    result = _run_gh_with_retry(
        ["gh", "api", "--method", "DELETE", f"repos/{{owner}}/{{repo}}/git/refs/{ref}"],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode == 0:
        console.print(f"[green]Deleted branch {branch} on GitHub[/green]")
    else:
        stderr = (result.stderr or "").strip()
        console.print(verbatim(f"Could not delete branch {branch} on GitHub: {stderr}", "yellow"))


def _finish_branch_in_worktree(
    pr_number: int, branch: str, worktree: Path, console: Console
) -> None:
    """Delete a merged PR's branch, which a linked worktree has checked out (#863).

    ``gh pr merge`` ran without ``--delete-branch``, so this deletes the branch
    on GitHub, then removes the worktree and the local branch. It never raises:
    the PR has merged, so a failure here is reported, not fatal.
    """
    console.print()
    try:
        merged_head = _merged_head(pr_number, console)
        if merged_head is None:
            console.print(
                verbatim(f"Left {branch} and its worktree {worktree} in place.", "yellow"),
                soft_wrap=True,
            )
            return
        _delete_remote_branch(branch, console)
        remove_merged_worktree(worktree, branch, merged_head, console)
    except subprocess.CalledProcessError as e:
        stderr = (e.stderr or "").strip() or str(e)
        console.print(verbatim(f"Cleanup after the merge failed: {stderr}", "yellow"))
    except OSError as e:
        console.print(verbatim(f"Cleanup after the merge failed: {e}", "yellow"))


def _current_branch() -> str | None:
    """Return the branch this checkout has checked out, or None when HEAD is detached."""
    try:
        result = subprocess.run(
            ["git", "branch", "--show-current"],
            capture_output=True,
            text=True,
            check=True,
        )
    except (subprocess.CalledProcessError, OSError):
        return None
    return result.stdout.strip() or None


def _fast_forward_base(base: str, console: Console) -> None:
    """Fast-forward this checkout's *base* branch to include the merge (#891).

    ``gh pr merge --delete-branch`` pulls the base only when it switches to it
    from the PR's branch. A checkout that is already on the base, which is where
    a worktree's PR is merged from, is otherwise left behind. It never raises:
    the PR has merged, so a failure here is reported, not fatal.
    """
    console.print()
    try:
        subprocess.run(
            ["git", "pull", "--ff-only", "origin", base],
            capture_output=True,
            text=True,
            check=True,
        )
    except (subprocess.CalledProcessError, OSError) as e:
        detail = (getattr(e, "stderr", None) or "").strip() or str(e)
        console.print(f"[yellow]Could not fast-forward {base}. Update it with:[/yellow]")
        console.print(f"  git pull --ff-only origin {base}")
        console.print(verbatim(detail, "yellow"))
        return
    console.print(f"[green]Fast-forwarded {base} to origin/{base}[/green]")


def _check_branch_up_to_date(current_branch: str, console: Console, base: str = "main") -> None:
    """Abort PR creation if the current branch is behind ``origin/<base>``.

    Fetches ``origin/<base>`` and compares it to ``HEAD``. If the branch is
    behind, prints the count, the missing commits, and the rebase command
    to run, then calls ``sys.exit(1)``. If the fetch itself fails (network
    down, unreachable remote), prints a warning and returns — a flaky
    network should not block PR creation.

    Args:
        current_branch: Name of the feature branch (used in remediation message).
        console: Rich console for output.
        base: Branch the PR will target: ``main``, or the ``doit pr --base`` value.
    """
    upstream = f"origin/{base}"
    try:
        subprocess.run(
            ["git", "fetch", "origin", base],
            check=True,
            capture_output=True,
            text=True,
        )
    except subprocess.CalledProcessError as e:
        stderr = (e.stderr or "").strip()
        console.print(verbatim(f"Warning: `git fetch origin {base}` failed: {stderr}", "yellow"))
        console.print("[yellow]Skipping up-to-date check; proceeding.[/yellow]")
        return

    count_result = subprocess.run(
        ["git", "rev-list", "--count", f"HEAD..{upstream}"],
        check=True,
        capture_output=True,
        text=True,
    )
    behind = int(count_result.stdout.strip() or "0")

    if behind == 0:
        console.print(f"[green]Branch is up to date with {upstream}.[/green]")
        return

    log_result = subprocess.run(
        ["git", "log", "--oneline", "-n", "10", f"HEAD..{upstream}"],
        check=True,
        capture_output=True,
        text=True,
    )

    console.print()
    console.print(f"[red]Branch is {behind} commit(s) behind {upstream}.[/red]")
    console.print("[dim]Missing commits:[/dim]")
    for line in log_result.stdout.strip().splitlines():
        console.print(verbatim(f"  {line}"))
    console.print()
    console.print("[yellow]Rebase and force-push, then re-run `doit pr`:[/yellow]")
    console.print(f"  git rebase {upstream} && git push --force-with-lease origin {current_branch}")
    console.print()
    console.print("[dim]Use `doit pr --no-update-check` to skip this check.[/dim]")
    sys.exit(1)


def _ensure_branch_pushed(current_branch: str, console: Console, no_push: bool) -> None:
    """Ensure the current branch has an upstream on ``origin``.

    If the branch already has an upstream, returns silently. Otherwise,
    runs ``git push -u origin <branch>`` to create it. On push failure,
    calls ``sys.exit(1)``.

    When ``no_push`` is True and the branch has no upstream, aborts with
    ``sys.exit(1)`` without attempting to push.

    Args:
        current_branch: Name of the branch to push.
        console: Rich console for output.
        no_push: If True, never push; abort if upstream is missing.
    """
    try:
        subprocess.run(
            ["git", "rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{u}"],
            check=True,
            capture_output=True,
            text=True,
        )
        return
    except subprocess.CalledProcessError:
        pass

    if no_push:
        console.print(
            f"[red]Branch '{current_branch}' has no upstream and --no-push was passed.[/red]"
        )
        console.print(f"[yellow]Push manually: git push -u origin {current_branch}[/yellow]")
        sys.exit(1)

    console.print(f"[dim]Pushing {current_branch} to origin...[/dim]")
    try:
        subprocess.run(
            ["git", "push", "-u", "origin", current_branch],
            check=True,
            capture_output=True,
            text=True,
        )
    except subprocess.CalledProcessError as e:
        stderr = (e.stderr or "").strip()
        console.print(f"[red]Failed to push {current_branch}:[/red]")
        console.print(verbatim(stderr, "red"))
        sys.exit(1)

    console.print(f"[dim]Pushed {current_branch} to origin.[/dim]")


def task_pr_merge() -> dict[str, Any]:
    """Merge a PR with properly formatted commit message.

    This task enforces the merge commit format:
        <type>: <subject> (merges PR #XX, addresses #YY)

    Uses squash merge with a custom subject line to ensure consistent
    commit history that matches the documented format.

    For a PR whose branch is checked out in a worktree under ``worktrees/``,
    run it from the main checkout: after the merge it removes the worktree and
    the branch. Run from inside the worktree, it prints how to (#863).

    Examples:
        doit pr_merge                    # Merge PR for current branch
        doit pr_merge --pr=123           # Merge specific PR
        doit pr_merge --delete-branch    # Also delete the branch after merge
        doit pr_merge --pr=123 --auto-close  # Close linked issues after merge
    """

    def merge_pr(
        pr: str | None = None,
        delete_branch: bool = True,
        auto_close: bool = False,
    ) -> None:
        console = Console()
        console.print()
        console.print(Panel.fit("[bold cyan]Merging Pull Request[/bold cyan]", border_style="cyan"))
        console.print()

        # Get PR info
        pr_info = _get_pr_info(pr, console)
        if not pr_info:
            sys.exit(1)

        pr_number = pr_info["number"]
        pr_title = pr_info["title"]
        pr_body = pr_info.get("body", "") or ""
        pr_state = pr_info.get("state", "")

        # The title is text, not markup: Rich drops `[tool.x]` as an unknown tag
        # and raises MarkupError on `[/x]`, so escape it wherever it is printed (#893).
        console.print(verbatim(f"PR #{pr_number}: {pr_title}", "dim"))

        # Check PR state
        if pr_state.upper() != "OPEN":
            console.print(f"[red]PR is not open (state: {pr_state}).[/red]")
            sys.exit(1)

        # GitHub merges a PR into its base. A PR built on another branch would
        # squash into that branch, and --auto-close would close issues that never
        # reached the default branch (#853).
        base = pr_info.get("baseRefName")
        if base:
            default_branch = _get_default_branch(console)
            if base != default_branch:
                console.print(
                    f"[red]PR #{pr_number} targets '{base}', not '{default_branch}'.[/red]"
                )
                console.print(
                    f"[yellow]doit pr_merge merges only into '{default_branch}'.[/yellow]"
                )
                console.print(
                    "[yellow]Merge the PR it builds on, rebase this branch onto "
                    f"'{default_branch}', then retarget it:[/yellow]"
                )
                console.print(f"  gh pr edit {pr_number} --base {default_branch}")
                sys.exit(1)

        # Validate PR title format.
        if not _PR_TITLE_PATTERN.match(pr_title):
            console.print("[red]PR title does not follow conventional commit format.[/red]")
            console.print("[yellow]Expected: <type>: <subject>[/yellow]")
            console.print("[yellow]Example: feat: add user authentication[/yellow]")
            sys.exit(1)

        # Extract linked issues
        issues = _extract_linked_issues(pr_body)
        if issues:
            console.print(f"[dim]Linked issues: {', '.join(f'#{i}' for i in issues)}[/dim]")
        else:
            console.print("[yellow]Warning: No linked issues found in PR body.[/yellow]")

        # Format merge subject
        merge_subject = _format_merge_subject(pr_title, pr_number, issues)
        console.print("\n[cyan]Merge commit subject:[/cyan]")
        console.print(verbatim(f"  {merge_subject}", "bold"))

        # Build merge command
        cmd = [
            "gh",
            "pr",
            "merge",
            str(pr_number),
            "--squash",
            "--subject",
            merge_subject,
        ]
        # gh's --delete-branch checks out the base branch in the checkout that
        # holds the PR's branch, then deletes the branch. In a linked worktree git
        # refuses that checkout while the base is checked out anywhere else, and
        # from any other checkout it refuses the delete. So a branch in a worktree
        # is deleted by the task, after the merge (#863).
        worktree = _worktree_holding(pr_info) if delete_branch else None
        if delete_branch and worktree is None:
            cmd.append("--delete-branch")

        # gh pulls the base only when --delete-branch switches to it from the PR's
        # branch, so a checkout that starts on the base is fast-forwarded by the
        # task after the merge (#891).
        start_branch = _current_branch() if base else None

        # Execute merge
        console.print("\n[cyan]Merging...[/cyan]")
        try:
            _run_gh_with_retry(cmd, check=True, capture_output=True, text=True)
            console.print()
            console.print(
                Panel.fit(
                    Text.assemble(
                        verbatim(f"PR #{pr_number} merged successfully!", "bold green"),
                        verbatim(f"\n\nCommit: {merge_subject}"),
                    ),
                    border_style="green",
                )
            )

            if auto_close:
                console.print()
                _close_linked_issues(issues, pr_number, console)
            else:
                # Reminder to update linked issues
                console.print()
                console.print(
                    Panel.fit(
                        "[bold yellow]Reminder: Update linked issues[/bold yellow]\n\n"
                        "Examples:\n"
                        f'  gh issue close <number> --comment "Addressed in PR #{pr_number}"\n'
                        f'  gh issue comment <number> --body "Addressed in PR #{pr_number}"',
                        border_style="yellow",
                    )
                )
        except subprocess.CalledProcessError as e:
            console.print("[red]Failed to merge PR.[/red]")
            if e.stderr:
                console.print(verbatim(e.stderr, "red"))
            if _STACKED_PR_MARKER in (e.stderr or "").lower():
                console.print(
                    "[yellow]This PR is part of a GitHub stack, which doit pr_merge does not "
                    "support.[/yellow]"
                )
                console.print(
                    "[yellow]GitHub merges stacked PRs only through its asynchronous merge "
                    "API.[/yellow]"
                )
                console.print(
                    "[yellow]Unstack it (gh-stack extension), then merge the PRs bottom "
                    "first:[/yellow]"
                )
                console.print("  gh stack unstack")
            sys.exit(1)

        # Outside the try: the PR has merged, so no failure from here on may be
        # reported as a failed merge.
        if worktree is not None:
            _finish_branch_in_worktree(pr_number, pr_info["headRefName"], worktree, console)
        if base and start_branch == base:
            _fast_forward_base(base, console)

    return {
        "actions": [merge_pr],
        "params": [
            {
                "name": "pr",
                "long": "pr",
                "default": None,
                "help": "PR number to merge (default: PR for current branch)",
            },
            {
                "name": "delete_branch",
                "long": "delete-branch",
                "type": bool,
                "default": True,
                "help": "Delete branch after merge (default: True)",
            },
            {
                "name": "auto_close",
                "long": "auto-close",
                "type": bool,
                "default": False,
                "help": "Close linked issues after merge with a standard comment",
            },
        ],
        "title": title_with_actions,
    }


def _load_labels_file(path: Path, console: Console) -> list[dict[str, str]]:
    """Parse a YAML labels file into a list of normalized label dicts.

    Each entry must be a mapping with a required ``name`` field. ``color``
    defaults to :data:`DEFAULT_LABEL_COLOR` and ``description`` defaults to
    an empty string. Extra fields are ignored. Malformed entries cause
    ``sys.exit(1)`` with a message naming the offending index.

    Args:
        path: Path to the labels YAML file.
        console: Rich console for error output.

    Returns:
        List of ``{"name": str, "color": str, "description": str}`` dicts.
    """
    if not path.exists():
        console.print(verbatim(f"Labels file not found: {path}", "red"))
        sys.exit(1)

    try:
        raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as e:
        console.print(verbatim(f"Failed to parse {path}: {e}", "red"))
        sys.exit(1)

    if raw is None:
        return []

    if not isinstance(raw, list):
        console.print(f"[red]Labels file must be a YAML list, got {type(raw).__name__}.[/red]")
        sys.exit(1)

    labels: list[dict[str, str]] = []
    for index, entry in enumerate(raw):
        if not isinstance(entry, dict):
            console.print(
                verbatim(
                    f"Labels file entry #{index} must be a mapping, got {type(entry).__name__}.",
                    "red",
                )
            )
            sys.exit(1)

        name = entry.get("name")
        if not isinstance(name, str) or not name.strip():
            console.print(
                verbatim(
                    f"Labels file entry #{index} is missing a 'name' field (entry: {entry!r}).",
                    "red",
                )
            )
            sys.exit(1)

        color_raw = entry.get("color", DEFAULT_LABEL_COLOR)
        if not isinstance(color_raw, str):
            console.print(
                verbatim(
                    f"Labels file entry '{name}' has a non-string 'color' "
                    f"(got {type(color_raw).__name__}).",
                    "red",
                )
            )
            sys.exit(1)

        description = entry.get("description", "")
        if description is None:
            description = ""
        if not isinstance(description, str):
            console.print(
                verbatim(
                    f"Labels file entry '{name}' has a non-string 'description' "
                    f"(got {type(description).__name__}).",
                    "red",
                )
            )
            sys.exit(1)

        labels.append(
            {
                "name": name.strip(),
                "color": color_raw.strip().lstrip("#").lower(),
                "description": description,
            }
        )

    return labels


def _fetch_github_labels(console: Console) -> dict[str, dict[str, str]]:
    """Fetch the current label set from GitHub via ``gh label list``.

    Parses the returned JSON into a ``{name: {color, description}}`` map
    with colors lowercased for case-insensitive comparison.

    Args:
        console: Rich console for error output.

    Returns:
        Dict keyed by label name.
    """
    try:
        result = _run_gh_with_retry(
            ["gh", "label", "list", "--limit", "200", "--json", "name,color,description"],
            check=True,
            capture_output=True,
            text=True,
        )
    except subprocess.CalledProcessError as e:
        stderr = (e.stderr or "").strip()
        console.print("[red]Failed to fetch labels from GitHub:[/red]")
        console.print(verbatim(stderr, "red"))
        sys.exit(1)

    try:
        data = json.loads(result.stdout or "[]")
    except json.JSONDecodeError as e:
        console.print(verbatim(f"Could not parse `gh label list` output: {e}", "red"))
        sys.exit(1)

    if not isinstance(data, list):
        console.print("[red]Unexpected `gh label list` output (not a list).[/red]")
        sys.exit(1)

    labels: dict[str, dict[str, str]] = {}
    for entry in data:
        if not isinstance(entry, dict):
            continue
        name = entry.get("name")
        if not isinstance(name, str):
            continue
        color = entry.get("color", "") or ""
        description = entry.get("description", "") or ""
        labels[name] = {
            "name": name,
            "color": str(color).lower(),
            "description": str(description),
        }
    return labels


def _reconcile_labels(
    desired: list[dict[str, str]],
    current: dict[str, dict[str, str]],
    *,
    prune: bool,
    dry_run: bool,
    console: Console,
) -> dict[str, int]:
    """Reconcile desired labels with the current GitHub state.

    Performs create/edit/delete operations (or prints the planned actions
    in ``dry_run`` mode). Colors are compared case-insensitively.

    Args:
        desired: Normalized list of labels from the YAML file.
        current: Map of current GitHub labels keyed by name.
        prune: If True, delete labels present on GitHub but absent from the file.
        dry_run: If True, print planned actions and make no mutating API calls.
        console: Rich console for output.

    Returns:
        Dict of counters: ``created``, ``updated``, ``unchanged``, ``deleted``, ``skipped``.
    """
    counters = {"created": 0, "updated": 0, "unchanged": 0, "deleted": 0, "skipped": 0}
    desired_names = {entry["name"] for entry in desired}

    for entry in desired:
        name = entry["name"]
        color = entry["color"]
        description = entry["description"]
        existing = current.get(name)

        if existing is None:
            prefix = "would create" if dry_run else "created"
            console.print(
                Text.assemble(
                    verbatim(f"+ {prefix}", "green"), verbatim(f" {name} (color={color})")
                )
            )
            counters["created"] += 1
            if not dry_run:
                _run_label_cmd(
                    [
                        "gh",
                        "label",
                        "create",
                        name,
                        "--color",
                        color,
                        "--description",
                        description,
                    ],
                    console,
                )
            continue

        if existing["color"] == color and existing["description"] == description:
            console.print(Text.assemble(verbatim("= no change", "dim"), verbatim(f" {name}")))
            counters["unchanged"] += 1
            continue

        prefix = "would update" if dry_run else "updated"
        console.print(
            Text.assemble(verbatim(f"~ {prefix}", "yellow"), verbatim(f" {name} (color={color})"))
        )
        counters["updated"] += 1
        if not dry_run:
            _run_label_cmd(
                [
                    "gh",
                    "label",
                    "edit",
                    name,
                    "--color",
                    color,
                    "--description",
                    description,
                ],
                console,
            )

    extras = sorted(set(current) - desired_names)
    for name in extras:
        if prune:
            prefix = "would delete" if dry_run else "deleted"
            console.print(Text.assemble(verbatim(f"- {prefix}", "red"), verbatim(f" {name}")))
            counters["deleted"] += 1
            if not dry_run:
                _run_label_cmd(["gh", "label", "delete", name, "--yes"], console)
        else:
            console.print(
                Text.assemble(
                    verbatim("? skipped", "dim"),
                    verbatim(f" {name} (not in file; use --prune to delete)"),
                )
            )
            counters["skipped"] += 1

    return counters


def _run_label_cmd(cmd: list[str], console: Console) -> None:
    """Invoke a ``gh label`` subcommand and abort on failure.

    Args:
        cmd: Full command argument list.
        console: Rich console for error output.
    """
    try:
        _run_gh_with_retry(cmd, check=True, capture_output=True, text=True)
    except subprocess.CalledProcessError as e:
        stderr = (e.stderr or "").strip()
        console.print(verbatim(f"Command failed: {' '.join(cmd)}", "red"))
        console.print(verbatim(stderr, "red"))
        sys.exit(1)


def _gh_repo_slug() -> str:
    """Return the ``owner/repo`` slug (nameWithOwner) for the current repository.

    Shells out to ``gh repo view --json nameWithOwner --jq .nameWithOwner`` so
    the helper picks up whichever remote ``gh`` is authenticated against —
    avoiding a hand-rolled parse of ``git remote get-url origin``.

    Returns:
        The ``owner/repo`` slug (for example ``endavis/pyproject-template``).

    Raises:
        subprocess.CalledProcessError: If ``gh repo view`` fails.
    """
    result = _run_gh_with_retry(
        ["gh", "repo", "view", "--json", "nameWithOwner", "--jq", ".nameWithOwner"],
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.strip()


def _gh_env_exists(repo_slug: str, name: str) -> bool:
    """Return True when the environment already exists on GitHub.

    Issues ``gh api repos/{repo_slug}/environments/{name} --silent`` with
    ``check=False``; the API returns 200 for an existing environment and 404
    otherwise. Only the exit code is inspected — the response body is
    discarded — so this works for any environment configuration.

    Args:
        repo_slug: ``owner/repo`` slug.
        name: Environment name.

    Returns:
        ``True`` if the environment exists, ``False`` otherwise.
    """
    result = _run_gh_with_retry(
        ["gh", "api", f"repos/{repo_slug}/environments/{name}", "--silent"],
        capture_output=True,
        text=True,
        check=False,
    )
    return result.returncode == 0


def _gh_env_create(repo_slug: str, name: str) -> None:
    """Create a GitHub environment with no protection rules.

    Issues ``gh api -X PUT repos/{repo_slug}/environments/{name}``. The
    GitHub API treats PUT on this endpoint as idempotent — a PUT to an
    existing environment returns 200 without resetting protection rules —
    but callers typically guard with :func:`_gh_env_exists` so the CLI can
    print a distinct ``created`` vs ``already exists`` message.

    Args:
        repo_slug: ``owner/repo`` slug.
        name: Environment name.

    Raises:
        subprocess.CalledProcessError: If the API call fails.
    """
    _run_gh_with_retry(
        ["gh", "api", "-X", "PUT", f"repos/{repo_slug}/environments/{name}"],
        capture_output=True,
        text=True,
        check=True,
    )


def _gh_env_list(repo_slug: str) -> list[str]:
    """Return the names of environments configured on the repository, sorted.

    Uses ``gh api repos/{repo_slug}/environments --jq .environments[].name``
    and returns the names in case-insensitive alphabetical order. An empty
    response yields an empty list.

    Args:
        repo_slug: ``owner/repo`` slug.

    Returns:
        Sorted list of environment names (may be empty).

    Raises:
        subprocess.CalledProcessError: If the API call fails.
    """
    result = _run_gh_with_retry(
        ["gh", "api", f"repos/{repo_slug}/environments", "--jq", ".environments[].name"],
        capture_output=True,
        text=True,
        check=True,
    )
    return sorted(line.strip() for line in result.stdout.splitlines() if line.strip())


def task_env_create() -> dict[str, Any]:
    """Create a GitHub environment by name (idempotent).

    Creates a repository environment via the GitHub API with no protection
    rules. If the environment already exists, prints a ``skipped`` message
    and returns without mutating anything.

    Examples:
        doit env_create --name=pypi
        doit env_create --name=testpypi
    """

    def create(name: str = "") -> None:
        console = Console()
        if not name:
            console.print("[red]--name is required[/red]")
            sys.exit(1)

        repo_slug = _gh_repo_slug()
        if _gh_env_exists(repo_slug, name):
            console.print(
                verbatim(f"Environment '{name}' already exists in {repo_slug} — skipped", "dim")
            )
            return

        _gh_env_create(repo_slug, name)
        console.print(verbatim(f"✓ Created environment '{name}' in {repo_slug}", "green"))

    return {
        "actions": [create],
        "params": [
            {
                "name": "name",
                "long": "name",
                "default": "",
                "help": "Environment name (for example 'pypi' or 'testpypi')",
            },
        ],
        "title": title_with_actions,
        "verbosity": 2,
    }


def task_env_list() -> dict[str, Any]:
    """List GitHub environments for the current repository.

    Prints a bulleted list of environment names (alphabetical). Prints a
    friendly warning and returns cleanly when the repository has none.

    Example:
        doit env_list
    """

    def list_envs() -> None:
        console = Console()
        repo_slug = _gh_repo_slug()
        names = _gh_env_list(repo_slug)
        if not names:
            console.print(f"[yellow]No environments in {repo_slug}[/yellow]")
            return

        console.print(f"[bold]Environments in {repo_slug}:[/bold]")
        for name in names:
            console.print(verbatim(f"  • {name}"))

    return {
        "actions": [list_envs],
        "title": title_with_actions,
        "verbosity": 2,
    }


def task_publish_setup() -> dict[str, Any]:
    """Bootstrap GitHub environments for PyPI/TestPyPI trusted publishing.

    Creates the ``testpypi`` and ``pypi`` environments (idempotent) and
    prints follow-up instructions for registering the project as a trusted
    publisher on TestPyPI and PyPI — a step that can only be done from the
    user's own PyPI session and is therefore explicitly out of scope for
    automation.

    Example:
        doit publish_setup
    """

    def setup() -> None:
        console = Console()
        repo_slug = _gh_repo_slug()
        for env_name in ("testpypi", "pypi"):
            if _gh_env_exists(repo_slug, env_name):
                console.print(f"[dim]• {env_name}: already exists[/dim]")
            else:
                _gh_env_create(repo_slug, env_name)
                console.print(f"[green]• {env_name}: created[/green]")

        owner, _, repo = repo_slug.partition("/")
        console.print()
        console.print(
            Panel.fit(
                "[bold]Next steps (manual, outside this tool):[/bold]\n\n"
                "  Register THREE trusted publishers — PyPI scopes them per\n"
                "  (owner, repo, workflow, environment) tuple, so each\n"
                "  (workflow, env) pair the template uses needs its own entry.\n\n"
                "  1. TestPyPI — workflow=testpypi.yml, env=testpypi\n"
                "     https://test.pypi.org/manage/account/publishing/\n"
                "     Purpose: pre-release uploads (v*-* tags).\n\n"
                "  2. TestPyPI — workflow=release.yml, env=testpypi\n"
                "     https://test.pypi.org/manage/account/publishing/\n"
                "     Purpose: production-release canary (release.yml uploads\n"
                "     to TestPyPI before PyPI as a sanity check).\n\n"
                "  3. PyPI — workflow=release.yml, env=pypi\n"
                "     https://pypi.org/manage/account/publishing/\n"
                "     Purpose: production-release publish.\n\n"
                "  Common fields for all three forms:\n"
                "     PyPI project name: (your pypi-name from pyproject.toml)\n"
                f"     Repository owner:  {owner}\n"
                f"     Repository name:   {repo}",
                border_style="cyan",
            )
        )

    return {
        "actions": [setup],
        "title": title_with_actions,
        "verbosity": 2,
    }


def task_labels_sync() -> dict[str, Any]:
    """Sync GitHub labels with ``.github/labels.yml`` (idempotent).

    Reads the labels file and reconciles the repository's GitHub labels:

    - Missing labels are created.
    - Labels whose color or description differ are updated.
    - Labels present on GitHub but absent from the file are left alone
      unless ``--prune`` is passed (then they are deleted).

    Color comparison is case-insensitive.

    Examples:
        doit labels_sync                        # Reconcile, do not prune.
        doit labels_sync --dry-run              # Preview changes only.
        doit labels_sync --prune                # Also delete extra labels.
        doit labels_sync --file=custom/labels.yml
    """

    def sync_labels(
        dry_run: bool = False,
        prune: bool = False,
        file: str = DEFAULT_LABELS_FILE,
    ) -> None:
        console = Console()
        console.print()
        mode = "(dry run)" if dry_run else ""
        console.print(
            Panel.fit(
                f"[bold cyan]Syncing GitHub Labels[/bold cyan] {mode}".rstrip(),
                border_style="cyan",
            )
        )
        console.print()

        try:
            desired = _load_labels_file(Path(file), console)
            if not desired:
                console.print(verbatim(f"No labels defined in {file}; nothing to sync.", "yellow"))
                return

            console.print(verbatim(f"Loaded {len(desired)} label(s) from {file}", "dim"))
            current = _fetch_github_labels(console)
            console.print(f"[dim]Fetched {len(current)} label(s) from GitHub[/dim]")
            console.print()

            counters = _reconcile_labels(
                desired,
                current,
                prune=prune,
                dry_run=dry_run,
                console=console,
            )

            console.print()
            summary = (
                f"{counters['created']} created, "
                f"{counters['updated']} updated, "
                f"{counters['unchanged']} unchanged, "
                f"{counters['deleted']} deleted, "
                f"{counters['skipped']} skipped"
            )
            console.print(
                Panel.fit(
                    f"[bold green]Label sync complete[/bold green]\n\n{summary}",
                    border_style="green",
                )
            )
        except SystemExit:
            raise
        except Exception as e:  # pragma: no cover - defensive catch-all
            console.print(verbatim(f"Unexpected error during label sync: {e}", "red"))
            sys.exit(1)

    return {
        "actions": [sync_labels],
        "params": [
            {
                "name": "dry_run",
                "long": "dry-run",
                "type": bool,
                "default": False,
                "help": "Print planned changes without calling gh label create/edit/delete",
            },
            {
                "name": "prune",
                "long": "prune",
                "type": bool,
                "default": False,
                "help": "Delete labels present on GitHub but absent from the file",
            },
            {
                "name": "file",
                "long": "file",
                "default": DEFAULT_LABELS_FILE,
                "help": f"Path to labels YAML file (default: {DEFAULT_LABELS_FILE})",
            },
        ],
        "title": title_with_actions,
    }
